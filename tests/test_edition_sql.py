"""The Sluaghbinder overlay: diffing upstream's two Edition databases into SQL."""
import sqlite3
import tempfile
import unittest
from pathlib import Path

from daoc_cli import edition_sql
from daoc_cli.errors import DaocError

SCHEMA = """
CREATE TABLE ServerProperty (ServerProperty_ID TEXT PRIMARY KEY, "Key" TEXT, Value TEXT);
CREATE TABLE Mob (Mob_ID TEXT PRIMARY KEY, Name TEXT, Level INTEGER, Note TEXT);
CREATE TABLE ClassXSpecialization (ClassXSpecialization_ID TEXT PRIMARY KEY, ClassID INTEGER, SpecKeyName TEXT);
CREATE TABLE Spell (Spell_ID INTEGER PRIMARY KEY, Name TEXT);
"""
PLAIN_ROWS = """
INSERT INTO ServerProperty VALUES ('p1', 'enable_sluaghbinder', 'False');
INSERT INTO ServerProperty VALUES ('p2', 'xp_rate', '1');
INSERT INTO Mob VALUES ('guard', 'Guard', 20, NULL);
INSERT INTO Spell VALUES (1, 'Heal');
"""


class DiffTest(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.dir = Path(tmp.name)
        self.plain = self.db("plain.db", PLAIN_ROWS)

    def db(self, name, rows):
        path = self.dir / name
        con = sqlite3.connect(str(path))
        con.executescript(SCHEMA + rows)
        con.commit()
        con.close()
        return path

    def b(self, extra):
        return self.db("b.db", PLAIN_ROWS + extra)

    def test_added_rows_become_inserts(self):
        b = self.b("INSERT INTO Mob VALUES ('sluaghbinder_trainer_tir_na_nog', 'O''Rourke', 50, NULL);")
        self.assertEqual(edition_sql.diff(b, self.plain), [
            'INSERT INTO "Mob" ("Mob_ID", "Name", "Level", "Note") '
            "VALUES ('sluaghbinder_trainer_tir_na_nog', 'O''Rourke', 50, NULL);",
        ])

    def test_changed_property_becomes_update(self):
        b = self.b("UPDATE ServerProperty SET Value='True' WHERE \"Key\"='enable_sluaghbinder';")
        self.assertEqual(edition_sql.diff(b, self.plain), [
            "UPDATE \"ServerProperty\" SET \"Value\"='True' WHERE \"Key\"='enable_sluaghbinder';",
        ])

    def test_rows_only_in_plain_become_deletes(self):
        b = self.b("DELETE FROM Mob WHERE Mob_ID='guard';")
        self.assertEqual(edition_sql.diff(b, self.plain), ["DELETE FROM \"Mob\" WHERE \"Mob_ID\"='guard';"])

    def test_changed_mob_becomes_update_by_pk(self):
        b = self.b("UPDATE Mob SET Level=21 WHERE Mob_ID='guard';")
        self.assertEqual(edition_sql.diff(b, self.plain), ["UPDATE \"Mob\" SET \"Level\"=21 WHERE \"Mob_ID\"='guard';"])

    def test_disallowed_table_fails_listing_it(self):
        b = self.b("INSERT INTO Spell VALUES (2, 'Plague'); INSERT INTO Spell VALUES (3, 'Wisp');")
        with self.assertRaises(DaocError) as cm:
            edition_sql.diff(b, self.plain)
        self.assertIn("Spell (2 rows)", cm.exception.msg)

    def test_disallowed_property_key_fails(self):
        b = self.b("UPDATE ServerProperty SET Value='2' WHERE \"Key\"='xp_rate';")
        with self.assertRaises(DaocError) as cm:
            edition_sql.diff(b, self.plain)
        self.assertIn("xp_rate", cm.exception.msg)

    def test_render_header_and_transaction(self):
        text = edition_sql.render(["SELECT 1;"], "b" * 64, "a" * 64)
        lines = text.splitlines()
        self.assertTrue(lines[0].startswith("-- generated by daoc dev edition-sql"))
        self.assertIn("b" * 64, text)
        self.assertIn("a" * 64, text)
        body = [line for line in lines if not line.startswith("--")]
        self.assertEqual(body, ["BEGIN;", "SELECT 1;", "COMMIT;"])

    def test_deterministic_order(self):
        b = self.b("INSERT INTO Mob VALUES ('z', 'Z', 1, NULL); INSERT INTO Mob VALUES ('a', 'A', 1, NULL);"
                   "INSERT INTO ClassXSpecialization VALUES ('c1', 63, 'Plague');"
                   "UPDATE ServerProperty SET Value='True' WHERE \"Key\"='enable_sluaghbinder';")
        statements = edition_sql.diff(b, self.plain)
        self.assertEqual([s.split(" (")[0].split(" SET")[0] for s in statements], [
            'INSERT INTO "ClassXSpecialization"', 'INSERT INTO "Mob"', 'INSERT INTO "Mob"', 'UPDATE "ServerProperty"'])
        self.assertLess(statements[1].index("'a'"), len(statements[1]))
        self.assertIn("'a'", statements[1])
        self.assertIn("'z'", statements[2])

    def test_applies_to_the_plain_world(self):
        b = self.b("INSERT INTO Mob VALUES ('wisp', 'Wisp', 1, NULL);"
                   "UPDATE ServerProperty SET Value='True' WHERE \"Key\"='enable_sluaghbinder';")
        sql = edition_sql.render(edition_sql.diff(b, self.plain), "b", "p")
        con = sqlite3.connect(str(self.plain))
        con.executescript(sql)
        self.assertEqual(con.execute("SELECT Value FROM ServerProperty WHERE \"Key\"='enable_sluaghbinder'")
                         .fetchone(), ("True",))
        self.assertEqual(con.execute("SELECT Name FROM Mob WHERE Mob_ID='wisp'").fetchone(), ("Wisp",))
        con.close()


if __name__ == "__main__":
    unittest.main()
